// Web Audio API Synthesizer for high-tech micro-interactions
let audioCtx = null;
let isSoundEnabled = false;

// Check localStorage on load if available
if (typeof window !== "undefined") {
  isSoundEnabled = localStorage.getItem("portfolio_sound_enabled") === "true";
}

const getAudioContext = () => {
  if (!audioCtx && typeof window !== "undefined") {
    const AudioContextClass = window.AudioContext || window.webkitAudioContext;
    if (AudioContextClass) {
      audioCtx = new AudioContextClass();
    }
  }
  if (audioCtx && audioCtx.state === "suspended") {
    audioCtx.resume();
  }
  return audioCtx;
};

export const getSoundEnabled = () => isSoundEnabled;

export const setSoundEnabled = (enabled) => {
  isSoundEnabled = enabled;
  if (typeof window !== "undefined") {
    localStorage.setItem("portfolio_sound_enabled", enabled ? "true" : "false");
  }
  if (enabled) {
    getAudioContext();
    playSuccessSound();
  }
};

export const playHoverSound = () => {
  if (!isSoundEnabled) return;
  try {
    const ctx = getAudioContext();
    if (!ctx) return;
    const osc = ctx.createOscillator();
    const gain = ctx.createGain();

    osc.type = "sine";
    osc.frequency.setValueAtTime(480, ctx.currentTime);
    osc.frequency.exponentialRampToValueAtTime(620, ctx.currentTime + 0.05);

    gain.gain.setValueAtTime(0.02, ctx.currentTime);
    gain.gain.exponentialRampToValueAtTime(0.0001, ctx.currentTime + 0.05);

    osc.connect(gain);
    gain.connect(ctx.destination);

    osc.start();
    osc.stop(ctx.currentTime + 0.05);
  } catch {
    // Ignore audio error
  }
};

